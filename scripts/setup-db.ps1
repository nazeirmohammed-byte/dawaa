$sqlcmd = (Get-Command sqlcmd -ErrorAction Stop).Source

function Invoke-Sql([string]$Query, [string]$Database = 'master') {
  & $sqlcmd -S "tcp:127.0.0.1,1433" -E -d $Database -b -l 8 -Q $Query
  if ($LASTEXITCODE -ne 0) { throw "sqlcmd failed ($LASTEXITCODE)" }
}

function Invoke-SqlFile([string]$Path) {
  & $sqlcmd -S "tcp:127.0.0.1,1433" -E -d dawaa -b -l 8 -i $Path
  if ($LASTEXITCODE -ne 0) { throw "sqlcmd failed for $Path" }
}

